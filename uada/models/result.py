"""
Result Models
=============
Models representing the output of each post-execution pipeline stage.

Chain:
  QueryExecutor   → QueryResult
  ResultAnalyser  → AnalysedResult
  VizGenerator    → VegaLiteSpec | VisualisationFallback
  ResponseAssembler → UADAResponse (returned to the API caller)
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


# ── Query Execution ───────────────────────────────────────────────────────────


class ColumnMeta(BaseModel):
    """Metadata for a single result column."""

    name: str
    data_type: str  # Python type name: "int", "float", "str", "datetime", "date", "bool"
    nullable: bool = True


class QueryResult(BaseModel):
    """
    The raw output of SQL execution.
    Produced by the Query Executor (step 7).
    """

    columns: list[ColumnMeta]
    rows: list[list[Any]] = Field(
        description="Row data as a list of lists. Each inner list corresponds to one row, "
        "values ordered by columns."
    )
    row_count: int
    is_truncated: bool = Field(
        default=False,
        description="True if the result was truncated at db_max_rows.",
    )
    truncated_at: int | None = Field(
        default=None,
        description="The row count limit that caused truncation.",
    )
    executed_sql: str = Field(description="The exact SQL that was executed.")
    execution_time_ms: float
    database_dialect: str

    @property
    def column_names(self) -> list[str]:
        return [c.name for c in self.columns]

    def is_empty(self) -> bool:
        return self.row_count == 0


class ExecutionError(BaseModel):
    """Structured description of a SQL execution failure."""

    error_type: str  # "syntax_error", "table_not_found", "column_not_found", "timeout", "other"
    message: str
    attempted_sql: str
    retry_hint: str | None = Field(
        default=None,
        description="Hint for the SQL repair loop, extracted from the error message.",
    )


# ── Result Analysis ───────────────────────────────────────────────────────────


class NumericSummary(BaseModel):
    """Statistical summary for a numeric column."""

    column: str
    min: float | None = None
    max: float | None = None
    mean: float | None = None
    median: float | None = None
    std: float | None = None
    sum: float | None = None
    null_count: int = 0


class TrendDirection(str, Enum):
    INCREASING = "increasing"
    DECREASING = "decreasing"
    STABLE = "stable"
    VOLATILE = "volatile"
    INSUFFICIENT_DATA = "insufficient_data"


class TrendAnalysis(BaseModel):
    """Simple trend analysis for time-series results."""

    column: str
    direction: TrendDirection
    change_pct: float | None = Field(
        default=None,
        description="Percentage change from first to last data point.",
    )
    note: str | None = None


class Outlier(BaseModel):
    """A detected outlier in the result set."""

    column: str
    row_index: int
    value: float
    z_score: float | None = None
    description: str


class AnalysedResult(BaseModel):
    """
    Post-processed query result with statistical summaries and insights.
    Produced by the Result Analyser (step 8).
    Consumed by the Visualisation Generator (step 9) and Response Assembler (step 10).
    """

    query_result: QueryResult

    # ── Statistical summaries ─────────────────────────────────────────────────
    numeric_summaries: list[NumericSummary] = Field(default_factory=list)
    trend_analysis: list[TrendAnalysis] = Field(default_factory=list)
    outliers: list[Outlier] = Field(default_factory=list)

    # ── Derived metadata ──────────────────────────────────────────────────────
    has_time_dimension: bool = False
    time_column: str | None = None
    has_comparison: bool = False

    # ── Narrative insight ─────────────────────────────────────────────────────
    narrative_insight: str | None = Field(
        default=None,
        description="1–2 sentence natural-language summary of the key finding. "
        "Generated by the Result Analyser from statistical summaries.",
    )
    key_finding: str | None = Field(
        default=None,
        description="The single most important data point. "
        "E.g. 'West region declined 23% vs prior quarter.'",
    )


# ── Visualisation ─────────────────────────────────────────────────────────────


class ChartType(str, Enum):
    """Supported Vega-Lite chart types."""
    BAR = "bar"
    LINE = "line"
    AREA = "area"
    POINT = "point"
    ARC = "arc"           # Pie / donut
    RECT = "rect"         # Heatmap
    BOXPLOT = "boxplot"
    RULE = "rule"         # Reference line


class VegaLiteSpec(BaseModel):
    """
    A validated Vega-Lite JSON specification.
    Produced by the Visualisation Generator (step 9).
    Sent directly to the frontend for rendering — no server-side rendering.
    """

    spec: dict[str, Any] = Field(
        description="Complete Vega-Lite JSON specification. "
        "Must contain: '$schema', 'mark', 'encoding'. "
        "Validated before returning to caller."
    )
    chart_type: ChartType
    title: str | None = None
    reasoning: str | None = Field(
        default=None,
        description="Why this chart type was selected. For tracing.",
    )

    def is_valid(self) -> tuple[bool, str | None]:
        """
        Structural validation of the Vega-Lite spec.
        Returns (True, None) if valid, (False, reason) if invalid.
        """
        required_keys = {"mark", "encoding"}
        missing = required_keys - set(self.spec.keys())
        if missing:
            return False, f"Missing required keys: {missing}"
        if "encoding" in self.spec:
            enc = self.spec["encoding"]
            if not isinstance(enc, dict):
                return False, "encoding must be an object"
        return True, None


class VisualisationFallback(BaseModel):
    """
    Returned when visualisation generation fails.
    The frontend renders this as a plain data table.
    """

    reason: str
    data_available: bool = True


# ── Final Response ─────────────────────────────────────────────────────────────


class PipelineStage(str, Enum):
    """Pipeline stage identifiers for error attribution."""
    SCHEMA_LINKING = "schema_linking"
    INTENT_EXTRACTION = "intent_extraction"
    QUERY_PLANNING = "query_planning"
    SQL_GENERATION = "sql_generation"
    SQL_VALIDATION = "sql_validation"
    QUERY_EXECUTION = "query_execution"
    RESULT_ANALYSIS = "result_analysis"
    VISUALISATION = "visualisation"


class UADAError(BaseModel):
    """Structured error returned to the API caller."""

    stage: PipelineStage
    error_type: str
    message: str
    user_message: str = Field(
        description="Human-readable message safe to display to the end user. "
        "Must not contain internal details, SQL, or stack traces."
    )
    is_retryable: bool = Field(
        default=False,
        description="True if the user can meaningfully retry the same request.",
    )
    clarification_needed: str | None = Field(
        default=None,
        description="If set, the user should answer this question before retrying.",
    )


class UADAResponse(BaseModel):
    """
    The complete response returned to the API caller.
    Every field is optional — partial responses are valid.
    The frontend renders whatever fields are present.
    """

    # ── Session ───────────────────────────────────────────────────────────────
    session_id: str
    turn_id: int
    timestamp: datetime

    # ── Success path ──────────────────────────────────────────────────────────
    answer: str | None = Field(
        default=None,
        description="Natural-language answer to the user's question.",
    )
    sql: str | None = Field(
        default=None,
        description="The SQL that was executed. Shown to the user on request.",
    )
    row_count: int | None = None
    is_truncated: bool = False
    execution_time_ms: float | None = None
    visualisation: VegaLiteSpec | VisualisationFallback | None = None
    key_finding: str | None = None

    # ── Error path ────────────────────────────────────────────────────────────
    error: UADAError | None = None

    # ── Metadata (for UI chrome) ──────────────────────────────────────────────
    question_type: str | None = None  # From AnalyticalIntent.question_type
    tables_used: list[str] = Field(default_factory=list)
    pipeline_duration_ms: float | None = None

    @property
    def is_success(self) -> bool:
        return self.error is None
